#!/usr/bin/env node
/**
 * generate-rust.js - Rust Client Generation Script (pilot)
 *
 * DESCRIPTION:
 *   Generates Rust models and a typed async client from the bundled OpenAPI
 *   specifications using progenitor (Oxide), pinned to an exact version in
 *   build/rust-gen/Cargo.toml + Cargo.lock and restated in
 *   build/lib/config.js (config.rust). This is the Rust counterpart of the
 *   Python pilot (build/generate-python.js): only the pilot constructs
 *   listed in config.rust.pilotPackages are generated.
 *
 * WHAT IT DOES:
 *   1. Resolves pilot constructs via build/lib/config.js discovery
 *   2. Checks the pinned toolchain (rust-toolchain.toml) and generator pin
 *   3. Builds the thin glue in build/rust-gen/ (cargo --locked) and runs it
 *      once per pilot spec into a temp staging dir. The glue fails on any
 *      spec progenitor rejects; any stderr output from it is an error
 *      (warnings-as-errors; nothing is written on failure)
 *   4. Adds the "generated, do not edit" header and formats the staged files
 *      with the pinned stable rustfmt
 *   5. Checks that the hand-maintained rust/Cargo.toml declares every
 *      dependency the generated code needs, verbatim
 *   6. Replaces rust/src/<construct>/ wholesale with the staged output
 *   7. Records generator, toolchain, spec digests, generated-file digests and
 *      the generated code's dependencies in rust/.rust-gen-manifest.json
 *
 * USAGE:
 *   node build/generate-rust.js
 *
 * PREREQUISITES:
 *   Run bundle-openapi.js first to generate the OpenAPI specs in _openapi_build/.
 *   rustup on PATH; the toolchain pinned in rust-toolchain.toml (with rustfmt,
 *   clippy and the wasm32-unknown-unknown target) installs on first use, or
 *   explicitly with `rustup toolchain install` from the repository root.
 *
 * OWNERSHIP:
 *   rust/src/<construct>/ and rust/.rust-gen-manifest.json are machine-owned:
 *   do not hand-edit them. rust/Cargo.toml, rust/src/lib.rs, rust/README.md
 *   and rust/tests/ are hand-maintained scaffolding; this script refuses to
 *   run when the scaffold is missing rather than creating it.
 *
 * OUTPUT:
 *   - rust/src/<construct>/ - generated models (types/) and client (mod.rs)
 *   - rust/.rust-gen-manifest.json - generation record
 */

const crypto = require("crypto");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");
const logger = require("./lib/logger");
const config = require("./lib/config");
const paths = require("./lib/paths");

const MANIFEST_FILENAME = ".rust-gen-manifest.json";
const CARGO_TOML = "Cargo.toml";
const LIB_RS = "src/lib.rs";
const GLUE_BINARY = "meshery-schemas-rust-gen";

/**
 * The header every generated Rust file starts with. It is deliberately not
 * `@generated`: rustfmt skips files carrying that marker, and the committed
 * output must stay under `cargo fmt --check`.
 *
 * @param {string} specRelative - Bundled spec path relative to the repo root
 * @returns {string} Header comment block, ending in a blank line
 */
function generatedHeader(specRelative) {
  return (
    `// Code generated by build/generate-rust.js with ${config.rust.generatorCrate} ` +
    `${config.rust.generatorVersion} from\n// ${specRelative}. DO NOT EDIT.\n` +
    "// Regenerate with `make generate-rust`.\n\n"
  );
}

/**
 * Read the toolchain channel from rust-toolchain.toml text. Only an exact
 * `x.y.z` release is accepted: `stable`, `nightly` or a bare `x.y` would let
 * the formatter, and so the committed output, drift between machines.
 *
 * @param {string} text - rust-toolchain.toml contents
 * @returns {string} The pinned channel, e.g. "1.99.1"
 */
function parseToolchainChannel(text) {
  const match = String(text).match(/^\s*channel\s*=\s*"([^"]+)"\s*$/m);
  if (!match) {
    throw new Error(`${config.paths.rustToolchainFile} has no [toolchain] channel`);
  }
  if (!/^\d+\.\d+\.\d+$/.test(match[1])) {
    throw new Error(
      `${config.paths.rustToolchainFile} channel must be an exact release (x.y.z), saw "${match[1]}"`,
    );
  }
  return match[1];
}

/**
 * Find the version of one package in a Cargo.lock.
 *
 * @param {string} lockText - Cargo.lock contents
 * @param {string} name - Package name
 * @returns {string[]} Every locked version of that package
 */
function lockedVersions(lockText, name) {
  const versions = [];
  for (const block of String(lockText).split(/\n(?=\[\[package\]\])/)) {
    const pkgName = block.match(/^name = "([^"]+)"$/m);
    const version = block.match(/^version = "([^"]+)"$/m);
    if (pkgName && version && pkgName[1] === name) {
      versions.push(version[1]);
    }
  }
  return versions;
}

/**
 * Return the lines of a Cargo.toml `[dependencies]` table (comments and
 * blank lines dropped, whitespace trimmed).
 *
 * @param {string} cargoToml - Cargo.toml contents
 * @returns {string[]} Dependency lines
 */
function dependencyTableLines(cargoToml) {
  const lines = [];
  let inTable = false;
  for (const raw of String(cargoToml).split("\n")) {
    const line = raw.trim();
    if (/^\[.*\]$/.test(line)) {
      inTable = line === "[dependencies]";
      continue;
    }
    if (inTable && line && !line.startsWith("#")) {
      lines.push(line);
    }
  }
  return lines;
}

/**
 * Dependency lines the generated code needs that the scaffold Cargo.toml
 * does not declare verbatim.
 *
 * @param {string[]} required - TOML inline lines reported by the glue
 * @param {string} cargoToml - rust/Cargo.toml contents
 * @returns {string[]} Missing lines
 */
function missingDependencyLines(required, cargoToml) {
  const declared = new Set(dependencyTableLines(cargoToml));
  return required.filter((line) => !declared.has(line));
}

/**
 * Resolve the pilot constructs from shared discovery.
 *
 * @returns {Array<{name: string, version: string, dirName: string, openapiPath: string}>}
 */
function getPilotPackages() {
  const wanted = new Set(config.rust.pilotPackages);
  const found = config.getSchemaPackages().filter((pkg) => wanted.has(`${pkg.version}/${pkg.dirName}`));
  const missing = [...wanted].filter(
    (key) => !found.some((pkg) => `${pkg.version}/${pkg.dirName}` === key),
  );
  if (missing.length > 0) {
    throw new Error(`Rust pilot constructs not discovered: ${missing.join(", ")}`);
  }
  return found;
}

/**
 * Digest a file with SHA-256 (hex).
 *
 * @param {string} absolutePath - File to digest
 * @returns {string} Hex digest
 */
function specDigest(absolutePath) {
  return crypto.createHash("sha256").update(fs.readFileSync(absolutePath)).digest("hex");
}

/**
 * List every file under the given directories, as paths relative to
 * `root` (POSIX separators, sorted).
 *
 * @param {string} root - Directory the paths are relative to
 * @param {string[]} dirs - Directories to walk
 * @returns {string[]} Relative file paths
 */
function listFiles(root, dirs) {
  const files = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else {
        files.push(full);
      }
    }
  };
  dirs.forEach(walk);
  return files.map((full) => path.relative(root, full).split(path.sep).join("/")).sort();
}

/**
 * Digest every file under each generated construct module, keyed by path
 * relative to rust/.
 *
 * @param {string} crateRoot - rust/ directory
 * @param {string[]} moduleDirs - Generated construct module directories
 * @returns {Object<string, string>} Relative path -> SHA-256 hex digest
 */
function generatedFileDigests(crateRoot, moduleDirs) {
  const digests = {};
  for (const relative of listFiles(crateRoot, moduleDirs)) {
    digests[relative] = specDigest(path.join(crateRoot, relative));
  }
  return digests;
}

/**
 * Run a command from the project root and fail loudly on a non-zero exit.
 *
 * @param {string} command - Executable
 * @param {string[]} args - Arguments
 * @param {Object} [options] - spawnSync options
 * @returns {{stdout: string, stderr: string}} Captured output
 */
function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: "utf-8", cwd: paths.getProjectRoot(), ...options });
  if (result.error) {
    throw new Error(`${command} could not be started: ${result.error.message}`);
  }
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed (exit ${result.status}):\n${result.stdout}${result.stderr}`);
  }
  return { stdout: result.stdout || "", stderr: result.stderr || "" };
}

/**
 * Check the Rust toolchain against rust-toolchain.toml and the generator
 * pin against build/rust-gen/Cargo.toml and Cargo.lock.
 *
 * @returns {{channel: string, rustc: string, rustfmt: string}} Observed versions
 */
function checkRustToolchain() {
  const toolchainPath = paths.fromRoot(config.paths.rustToolchainFile);
  if (!paths.fileExists(toolchainPath)) {
    throw new Error(`${config.paths.rustToolchainFile} not found at the repository root`);
  }
  const channel = parseToolchainChannel(fs.readFileSync(toolchainPath, "utf-8"));
  const installHint =
    "Install rustup (https://rustup.rs), then run `rustup toolchain install` from the repository root " +
    `to install the toolchain pinned in ${config.paths.rustToolchainFile}.`;

  const rustc = spawnSync("rustc", ["--version"], { encoding: "utf-8", cwd: paths.getProjectRoot() });
  const rustcVersion = `${rustc.stdout || ""}${rustc.stderr || ""}`.trim();
  if (rustc.error || rustc.status !== 0) {
    throw new Error(`rustc is not usable (${rustcVersion || rustc.error?.message || "no output"}). ${installHint}`);
  }
  if (!rustcVersion.startsWith(`rustc ${channel} `)) {
    throw new Error(`rustc ${channel} is required (saw: ${rustcVersion}). ${installHint}`);
  }

  const rustfmt = spawnSync("rustfmt", ["--version"], { encoding: "utf-8", cwd: paths.getProjectRoot() });
  const rustfmtVersion = `${rustfmt.stdout || ""}${rustfmt.stderr || ""}`.trim();
  if (rustfmt.error || rustfmt.status !== 0) {
    throw new Error(`rustfmt is not usable (${rustfmtVersion || "no output"}). ${installHint}`);
  }

  const pin = `=${config.rust.generatorVersion}`;
  const glueToml = fs.readFileSync(paths.fromRoot(config.paths.rustGenDir, CARGO_TOML), "utf-8");
  const declared = dependencyTableLines(glueToml).find((line) => line.startsWith(`${config.rust.generatorCrate} =`));
  if (!declared || !declared.includes(`"${pin}"`)) {
    throw new Error(
      `${config.paths.rustGenDir}/${CARGO_TOML} must pin ${config.rust.generatorCrate} to "${pin}" ` +
        `(config.rust.generatorVersion); saw: ${declared || "no entry"}`,
    );
  }
  const lockText = fs.readFileSync(paths.fromRoot(config.paths.rustGenDir, "Cargo.lock"), "utf-8");
  const locked = lockedVersions(lockText, config.rust.generatorCrate);
  if (locked.length !== 1 || locked[0] !== config.rust.generatorVersion) {
    throw new Error(
      `${config.paths.rustGenDir}/Cargo.lock must lock ${config.rust.generatorCrate} ` +
        `${config.rust.generatorVersion} (saw: ${locked.join(", ") || "none"})`,
    );
  }

  return { channel, rustc: rustcVersion, rustfmt: rustfmtVersion };
}

/**
 * Check generation prerequisites: bundled specs and hand-maintained scaffolding.
 *
 * @param {Array} pilotPackages - Resolved pilot constructs
 */
function checkRustPrerequisites(pilotPackages) {
  const buildDir = paths.fromRoot(config.paths.buildDir);
  if (!paths.dirExists(buildDir)) {
    throw new Error("_openapi_build/ directory not found. Run 'node build/bundle-openapi.js' first.");
  }

  for (const pkg of pilotPackages) {
    const specPath = paths.fromRoot(config.getBundledOutputPath(pkg));
    if (!paths.fileExists(specPath)) {
      throw new Error(`${config.getBundledOutputPath(pkg)} not found. Run 'node build/bundle-openapi.js' first.`);
    }
  }

  // Hand-maintained scaffolding must already exist; generation never creates it.
  for (const scaffold of [CARGO_TOML, LIB_RS]) {
    if (!paths.fileExists(paths.fromRoot(config.paths.rustDir, scaffold))) {
      throw new Error(`Hand-maintained scaffold missing: ${config.paths.rustDir}/${scaffold}`);
    }
  }
}

/**
 * Build the glue crate once (locked) and return its binary path.
 *
 * @returns {string} Absolute path of the glue binary
 */
function buildGlue() {
  const manifestPath = paths.fromRoot(config.paths.rustGenDir, CARGO_TOML);
  const targetDir = paths.fromRoot(config.paths.rustGenDir, "target");
  logger.step(`Building ${config.paths.rustGenDir} (${config.rust.generatorCrate} ${config.rust.generatorVersion})...`);
  run("cargo", ["build", "--locked", "--quiet", "--manifest-path", manifestPath], {
    env: { ...process.env, CARGO_TARGET_DIR: targetDir },
  });
  return path.join(targetDir, "debug", process.platform === "win32" ? `${GLUE_BINARY}.exe` : GLUE_BINARY);
}

/**
 * Generate one pilot construct into a staging directory and format it.
 *
 * @param {string} glue - Glue binary path
 * @param {Object} pkg - Package definition
 * @param {string} stagingRoot - Temp directory holding per-package output
 * @returns {{dependencies: string[], stagedDir: string}} Generator record
 */
function generatePilotPackage(glue, pkg, stagingRoot) {
  const specRelative = config.getBundledOutputPath(pkg);
  const stagedDir = path.join(stagingRoot, `${pkg.version}-${pkg.name}`);

  logger.step(`Generating Rust client: ${pkg.name} (${pkg.version})...`);

  const { stdout, stderr } = run(glue, [paths.fromRoot(specRelative), stagedDir]);
  if (stderr.trim() !== "") {
    throw new Error(`Rust generation for ${pkg.version}/${pkg.dirName} wrote to stderr (treated as an error):\n${stderr}`);
  }
  let report;
  try {
    report = JSON.parse(stdout);
  } catch (err) {
    throw new Error(`Rust generation for ${pkg.version}/${pkg.dirName} printed no dependency report: ${err.message}`);
  }
  const dependencies = report.dependencies.map((dep) => dep.toml).sort();

  const header = generatedHeader(specRelative);
  const files = listFiles(stagedDir, [stagedDir]);
  for (const relative of files) {
    const full = path.join(stagedDir, relative);
    fs.writeFileSync(full, header + fs.readFileSync(full, "utf-8"), "utf-8");
  }
  // rustfmt follows `mod` declarations from mod.rs, so one call formats the
  // whole construct module. It runs from the repository root, so rustup
  // selects the toolchain pinned in rust-toolchain.toml.
  run("rustfmt", ["--edition", "2024", path.join(stagedDir, "mod.rs")]);

  logger.success(`Generated: ${pkg.version}/${pkg.name} (${files.length} file(s))`);
  return { dependencies, stagedDir };
}

/**
 * Copy a staged module tree into the crate, skipping dotfiles.
 *
 * @param {string} src - Staged module root
 * @param {string} dest - Crate module directory
 */
function copyStagedTree(src, dest) {
  paths.ensureDir(dest);
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) {
      continue;
    }
    const from = path.join(src, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyStagedTree(from, to);
    } else if (entry.isFile()) {
      fs.copyFileSync(from, to);
    }
  }
}

/**
 * Assemble the crate from staged output. Enforcement first: a dependency
 * the scaffold Cargo.toml does not declare aborts before rust/ is touched.
 * Then each construct module is replaced wholesale (stale files cannot
 * linger) and the manifest is rewritten.
 *
 * @param {Array} pilotPackages - Resolved pilot constructs
 * @param {Map} stagedByKey - "version/dirName" -> generator record
 * @param {{channel: string, rustc: string, rustfmt: string}} toolchain - Observed versions
 */
function assembleCrate(pilotPackages, stagedByKey, toolchain) {
  const crateRoot = paths.fromRoot(config.paths.rustDir);
  const cargoToml = fs.readFileSync(path.join(crateRoot, CARGO_TOML), "utf-8");

  const missing = new Set();
  for (const record of stagedByKey.values()) {
    missingDependencyLines(record.dependencies, cargoToml).forEach((line) => missing.add(line));
  }
  if (missing.size > 0) {
    throw new Error(
      `${config.paths.rustDir}/${CARGO_TOML} [dependencies] must declare, verbatim, what the generated code needs:\n` +
        [...missing].map((line) => `  ${line}`).join("\n"),
    );
  }

  const specs = {};
  const dependencies = {};
  const moduleDirs = [];
  for (const pkg of pilotPackages) {
    const key = `${pkg.version}/${pkg.dirName}`;
    const record = stagedByKey.get(key);
    const specRelative = config.getBundledOutputPath(pkg);
    specs[key] = { spec: specRelative, sha256: specDigest(paths.fromRoot(specRelative)) };
    dependencies[key] = record.dependencies;

    const destDir = path.join(crateRoot, "src", pkg.name);
    paths.removeDir(destDir);
    copyStagedTree(record.stagedDir, destDir);
    moduleDirs.push(destDir);
    logger.success(`Assembled: ${paths.relativePath(destDir)}`);
  }

  const manifest = {
    generator: config.rust.generatorCrate,
    generatorVersion: config.rust.generatorVersion,
    interface: config.rust.interface,
    tags: config.rust.tags,
    toolchain: toolchain.channel,
    specs,
    files: generatedFileDigests(crateRoot, moduleDirs),
    dependencies,
  };
  const manifestPath = path.join(crateRoot, MANIFEST_FILENAME);
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf-8");
  logger.success(`Wrote: ${paths.relativePath(manifestPath)}`);
  logger.info(`Toolchain: ${toolchain.rustc} / ${toolchain.rustfmt}`);
}

/**
 * Main entry point
 */
async function main() {
  const startTime = Date.now();

  try {
    process.chdir(paths.getProjectRoot());

    logger.header("🦀 Generating Rust clients (pilot)...");

    const pilotPackages = getPilotPackages();
    logger.info(`Pilot constructs: ${pilotPackages.map((pkg) => `${pkg.version}/${pkg.dirName}`).join(", ")}`);

    checkRustPrerequisites(pilotPackages);
    const toolchain = checkRustToolchain();
    const glue = buildGlue();

    const stagingRoot = fs.mkdtempSync(path.join(os.tmpdir(), "meshery-rust-client-"));
    try {
      const stagedByKey = new Map();
      for (const pkg of pilotPackages) {
        stagedByKey.set(`${pkg.version}/${pkg.dirName}`, generatePilotPackage(glue, pkg, stagingRoot));
      }
      assembleCrate(pilotPackages, stagedByKey, toolchain);
    } finally {
      fs.rmSync(stagingRoot, { recursive: true, force: true });
    }

    const duration = ((Date.now() - startTime) / 1000).toFixed(2);
    logger.blank();
    logger.success(`Rust client generation complete! (${duration}s)`);
  } catch (err) {
    logger.error(err.message);
    process.exit(1);
  }
}


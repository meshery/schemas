const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const config = require("../build/lib/config");
const {
  findOrphanedOutputDirs,
  pruneOrphanedGoOutputs,
  pruneOrphanedTypescriptOutputs,
} = require("../build/lib/generated-outputs");

const OAPI_HEADER = "// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.5.1 DO NOT EDIT.\n";
const HELPER_HEADER = "// Code generated by build/generate-golang.js; DO NOT EDIT.\n";

function write(root, relativePath, contents = "") {
  const full = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, contents, "utf-8");
}

// A checkout with one live construct, one removed construct, one construct in
// excludePackages, and one whose package name is overridden (design -> pattern).
function withFixture(fn) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "schemas-generated-outputs-"));
  try {
    write(root, "schemas/constructs/v1beta3/live/api.yml");
    write(root, "schemas/constructs/v1beta1/relationship/api.yml");
    write(root, "schemas/constructs/v1beta1/design/api.yml");

    for (const name of ["live", "removed"]) {
      write(root, `models/v1beta3/${name}/${name}.go`, `// Package ${name}\n//\n${OAPI_HEADER}package ${name}\n`);
      write(root, `models/v1beta3/${name}/zz_generated.helpers.go`, `${HELPER_HEADER}package ${name}\n`);
      write(root, `typescript/generated/v1beta3/${name}/Type.ts`, "export {};\n");
    }
    write(root, "models/v1beta1/pattern/pattern.go", `${OAPI_HEADER}package pattern\n`);
    write(root, "typescript/generated/v1beta1/pattern/Pattern.ts", "export {};\n");
    write(root, "typescript/generated/v1beta1/relationship/Relationship.ts", "export {};\n");
    // Unversioned hand-maintained packages are not construct output.
    write(root, "models/core/helpers.go", "package core\n");
    write(root, "models/permissions/permissions.go", "package permissions\n");

    return fn(root);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
}

test("getConstructOutputKeys counts excluded constructs and applies package name overrides", () => {
  withFixture((root) => {
    assert.deepEqual(
      [...config.getConstructOutputKeys(root)].sort(),
      ["v1beta1/pattern", "v1beta1/relationship", "v1beta3/live"],
    );
  });
});

test("findOrphanedOutputDirs reports only output whose construct was removed", () => {
  withFixture((root) => {
    assert.deepEqual(findOrphanedOutputDirs(root, "models"), ["models/v1beta3/removed"]);
    assert.deepEqual(findOrphanedOutputDirs(root, "typescript/generated"), [
      "typescript/generated/v1beta3/removed",
    ]);
  });
});

test("pruneOrphanedGoOutputs deletes a removed construct's generated package and keeps the rest", () => {
  withFixture((root) => {
    assert.deepEqual(pruneOrphanedGoOutputs(root), ["models/v1beta3/removed"]);
    assert.equal(fs.existsSync(path.join(root, "models/v1beta3/removed")), false);
    assert.equal(fs.existsSync(path.join(root, "models/v1beta3/live/live.go")), true);
    assert.equal(fs.existsSync(path.join(root, "models/v1beta1/pattern/pattern.go")), true);
    assert.equal(fs.existsSync(path.join(root, "models/core/helpers.go")), true);
  });
});

test("pruneOrphanedGoOutputs refuses to leave a hand-written file in a removed package", () => {
  withFixture((root) => {
    write(root, "models/v1beta3/removed/helpers.go", "package removed\n\nfunc Helper() {}\n");
    assert.throws(() => pruneOrphanedGoOutputs(root), /models\/v1beta3\/removed\/helpers\.go/);
    assert.equal(fs.existsSync(path.join(root, "models/v1beta3/removed/helpers.go")), true);
  });
});

test("pruneOrphanedTypescriptOutputs deletes a removed construct's types and keeps excluded constructs", () => {
  withFixture((root) => {
    assert.deepEqual(pruneOrphanedTypescriptOutputs(root), ["typescript/generated/v1beta3/removed"]);
    assert.equal(fs.existsSync(path.join(root, "typescript/generated/v1beta3/removed")), false);
    assert.equal(fs.existsSync(path.join(root, "typescript/generated/v1beta3/live/Type.ts")), true);
    assert.equal(fs.existsSync(path.join(root, "typescript/generated/v1beta1/relationship/Relationship.ts")), true);
  });
});

// Removing a construct removes its generated output in the same change. The
// artifacts workflow regenerates on master, but nothing else deletes output,
// and tsup publishes every file under typescript/generated/.
test("this checkout has no generated output for a removed construct", () => {
  const root = config.getProjectRoot();
  assert.deepEqual(
    [...findOrphanedOutputDirs(root, config.paths.modelsDir), ...findOrphanedOutputDirs(root, config.paths.typescriptDir)],
    [],
    "Run `make build` (or delete these directories) in the change that removes the construct.",
  );
});
